export type Category = Chart;

/**
 * Which roster the run is built from.
 *
 *   real  — the named roster, with photographs, biographies and
 *           catalogues fetched from Wikipedia and MusicBrainz. The default,
 *           and appropriate for private use.
 *   demo  — generated names, no real people, no outbound requests at all.
 *           Intended for anywhere the app is publicly reachable, where
 *           attaching simulated career-death events to named living people is
 *           not something to publish.
 *
 * Set ROSTER_MODE=demo to switch. The market, the engine and every quantitative
 * tool behave identically either way — only the names and the profile lookups
 * change.
 */
export type RosterMode = "real" | "demo";

export function rosterMode(): RosterMode {
  return process.env.ROSTER_MODE === "demo" ? "demo" : "real";
}

export function isDemo(): boolean {
  return rosterMode() === "demo";
}

/** Universe size for the current mode. */
export function universeSize(): number {
  return isDemo() ? 520 : ROSTER.length;
}

const RAP_SET = new Set<string>([...ROSTER_RAP, ...ROSTER_RAP_ADDED, ...ROSTER_RAP_ADDED_2]);
const HOUSE_SET = new Set<string>([...ROSTER_HOUSE, ...ROSTER_HOUSE_ADDED_2]);

/** Which chart an artist belongs to. */
export function categoryOf(name: string): Category {
  const e = EXPANSION_BY_NAME.get(name);
  if (e) return e.chart;
  if (HOUSE_SET.has(name)) return "house";
  return RAP_SET.has(name) ? "rap" : "rnb";
}

/**
 * Genre pools, kept separate per category.
 *
 * Genre used to be drawn from one combined pool, which is how a rap artist
 * ended up filed under neo-soul. Harmless while genre was decoration; not
 * harmless once the rankings can be filtered by chart.
 */
export const RAP_GENRES = [
  "drill", "trap", "boom bap", "emo rap", "gospel rap", "phonk",
  "jersey club", "conscious rap", "horrorcore", "g-funk",
];
export const RNB_GENRES = [
  "neo-soul", "alt-R&B", "trap soul", "contemporary R&B", "quiet storm",
  "gospel soul", "funk", "new jack swing",
];
export const HOUSE_GENRES = [
  "house", "tech house", "deep house", "UK garage", "bass house",
  "minimal house", "acid house", "speed garage",
];

/**
 * Deterministic genre for a name, drawn from its own category's pool.
 *
 * Derived rather than stored so existing runs pick up the correction without a
 * reseed — the genre column on Artist predates the split and is no longer read
 * for display.
 */
export function genreFor(name: string): string {
  const curated = EXPANSION_BY_NAME.get(name)?.genre;
  if (curated) return curated;
  const c = categoryOf(name);
  const pool = c === "rap" ? RAP_GENRES : c === "house" ? HOUSE_GENRES : RNB_GENRES;
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0;
  return pool[h % pool.length];
}

