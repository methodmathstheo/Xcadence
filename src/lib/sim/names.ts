/**
 * Everything listed, hand-written names first and generated additions after,
 * so adding to either never moves an existing index — and with it the seeded
 * parameters a reseed would reproduce.
 */
export const ROSTER: readonly string[] = [...ROSTER_BASE, ...EXPANSION.map((e) => e.name)];

/** Spotify monthly listeners at the snapshot, or null where none is public. */
export function listenersFor(name: string): number | null {
  const e = EXPANSION_BY_NAME.get(name);
  if (e?.listeners) return e.listeners;
  const base = LISTENERS_BASE[name];
  return typeof base === "number" && base > 0 ? base : null;
}

